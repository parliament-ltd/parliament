// Scheme definitions for Parliament V2 (PR-4b).
//
// Six schemes, each with four a11y variants (light, dark, light-hc, dark-hc)
// per architecture §6g. Used for two purposes:
//   1. Seeding the librarySchemes IndexedDB store at first boot (snapshot
//      metadata — version, displayName, description, the variant token
//      maps). The future editor / wizard reads this catalog to render the
//      scheme picker.
//   2. Reference for the per-scheme CSS blocks in src/index.css. The CSS is
//      the actual runtime source of truth for visual rendering — this file
//      mirrors it as JSON-shaped data. Keep in sync when token values
//      change. (A future PR may auto-generate the CSS from this file; for
//      Phase 1 they are dual-maintained.)
//
// ─── Naming caveat ────────────────────────────────────────────────────
//
// The accent token is named `gold` for backwards compatibility with the
// existing Parliament-only codebase. In non-Parliament schemes the value
// is NOT gold (e.g. Cool Bright is blue, Deep Calm is sage-blue, Fresh
// Teal is teal, etc.). Components reading `var(--p-gold)` get the right
// active-scheme accent regardless of the variable name. A future refactor
// may rename to `--p-accent` and migrate call sites; out of Phase 1 scope.
//
// ─── Sources for accent values ────────────────────────────────────────
//
// Parliament: existing src/index.css (PR-4a).
// Cool Bright, Deep Calm, Fresh Teal, Amber Glow: drawn from the SCHEME_PALETTES
//   dict in refactor/parliament_editor_v2.html (the canonical scheme picker
//   spec). Stripped to accent + bg + text fields.
// Soft Violet: drawn from refactor/parliament_wizard_v5.html scheme card
//   (the editor mockup omits Soft Violet per parliament_mode_file_format.md §1).
//
// Everything else (full bg/text scales, all 4 HC variants, blueprint
// tokens for the 5 new schemes, data-series tokens for all 6) is derived
// here for the first time. Flagged explicitly in the PR description for
// design review.

