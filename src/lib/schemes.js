/**
 * Look up a scheme definition by id.
 * @param {string} id e.g. 'cool-bright@1.0'
 */
export function getSchemeDefinition(id) {
  return SCHEMES.find(s => s.id === id) || null
}

/**
 * Bare scheme name (without `@version`) — used by data-scheme attribute.
 * @param {string} id e.g. 'cool-bright@1.0' → 'cool-bright'
 */
export function schemeName(id) {
  return id.split('@')[0]
}
