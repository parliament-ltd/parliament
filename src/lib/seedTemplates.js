// libraryRooms id, displayName, description, icon, status, and the full
// layout/scheme/components shape that `modes.createModeFromTemplate()`
// will splice into a fresh mode record on instantiation.
//
// Per [phase-1-pr-plan.md](refactor/phase-1-pr-plan.md) PR-9:
//   - 5 available templates (Writing Studio, Data Workspace, Drafting
//     Desk, Pocket Chat, Quiet Room).
//   - 2 coming-soon templates (Kingfisher: deep reading, Starling:
//     collaboration) point at coming-soon layouts seeded by PR-1.
//   - All available templates default to `parliament@1.0` per NQ-9.
//
// Several templates have empty layout slots that catalog components
// haven't filled in yet — Writing Studio's outline, Data Workspace's
// file-shelf / canvas, Drafting Desk's document / margin. Those slots
// fill out as the catalog grows: PR-11a adds Pelican-derived
// components (file-shelf, chart-canvas, table-canvas, column-inspector)
// and updates Data Workspace; PR-11b adds Secretarybird-derived
// components (document-canvas, claude-comments, ripple-analysis) and
// updates Drafting Desk. Until then the rooms render as a working chat
// inside the right layout, which is the minimum useful state.

