// Helper: a fresh component spec inside a template. Real component ids
// are generated by createModeFromTemplate(); these placeholders only
// need to be unique within the template so duplicate refs in the same
// template (rare, but legal) don't collide.
function comp(localId, ref, slot, order, config = {}) {
  return { id: `tmpl_${localId}`, ref, slot, order, config }
}

